#ifndef LLVM_LIB_TARGET_CELLSPU_MCTARGETDESC_SPUINSTPRINTER_H
#define LLVM_LIB_TARGET_CELLSPU_MCTARGETDESC_SPUINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class SPUInstPrinter : public MCInstPrinter {
public:
  SPUInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annotation,
                 const MCSubtargetInfo &STI, raw_ostream &OS) override;
  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void PrintSpecial(const MCInst *MI, raw_ostream &OS, const char *Code);

  void printU7ImmOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printS10ImmOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printU10ImmOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printS16ImmOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printU16ImmOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printU18ImmOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printShufAddr(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printMemRegReg(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printDFormAddr(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printAddr256K(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printCallOperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printHBROperand(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printPCRelativeOperand(const MCInst *MI, unsigned OpNo,
                              raw_ostream &OS);
  void printSymbolHi(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printSymbolLo(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printSymbolLSA(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printROTHNeg7Imm(const MCInst *MI, unsigned OpNo, raw_ostream &OS);
  void printROTNeg7Imm(const MCInst *MI, unsigned OpNo, raw_ostream &OS);

  // Autogenerated by TableGen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               raw_ostream &OS);
  static const char *getRegisterName(MCRegister Reg);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_CELLSPU_MCTARGETDESC_SPUINSTPRINTER_H
